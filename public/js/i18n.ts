export const DICTIONARIES = Object.freeze({
  tr: Object.freeze(tr),
  en: Object.freeze(en),
  es: Object.freeze(es),
  ru: Object.freeze(ru),
});
const STORAGE_KEY = 'cm:locale:v1';

export const SUPPORTED_LOCALES = Object.freeze(['auto', 'tr', 'en', 'es', 'ru']);

export function supportedLocale(value) {
  const str = String(value || '')
    .toLowerCase()
    .trim();
  if (str === 'auto') return 'auto';
  if (str.startsWith('es')) return 'es';
  if (str.startsWith('ru')) return 'ru';
  if (str.startsWith('en')) return 'en';
  return 'tr';
}

export function resolveLocale(value, navigatorLanguage = 'tr') {
  const loc = supportedLocale(value);
  if (loc === 'auto') return supportedLocale(navigatorLanguage);
  return loc;
}

export function createI18n({
  storage = globalThis.localStorage,
  navigatorLanguage = 'tr',
  document,
}: any = {}) {
  let rawStored = null;
  try {
    rawStored = storage?.getItem?.(STORAGE_KEY);
  } catch {
    // Storage can be unavailable in hardened browser contexts.
  }
  // On first visit (no stored value) default to 'auto' so navigator language is respected.
  // 'auto' means: always resolve to navigatorLanguage.
  let stored = rawStored ? supportedLocale(rawStored) : 'auto';
  let current = resolveLocale(stored, navigatorLanguage);
  const subscribers = new Set<any>();

  function t(key, variables = {}) {
    const template = DICTIONARIES[current][key] ?? DICTIONARIES.tr[key] ?? key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, name) =>
      Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
    );
  }

  function refresh() {
    if (!document) return;
    document.documentElement.lang = current;
    for (const node of document.querySelectorAll(
      '[data-i18n], [data-i18n-aria-label], [data-i18n-title], [data-i18n-placeholder]'
    )) {
      if (node.dataset.i18n) node.textContent = t(node.dataset.i18n);
      if (node.dataset.i18nAriaLabel)
        node.setAttribute?.('aria-label', t(node.dataset.i18nAriaLabel));
      if (node.dataset.i18nTitle) node.setAttribute?.('title', t(node.dataset.i18nTitle));
      if (node.dataset.i18nPlaceholder)
        node.setAttribute?.('placeholder', t(node.dataset.i18nPlaceholder));
    }
  }

  function setLocale(value) {
    const nextStored = supportedLocale(value);
    const nextResolved = resolveLocale(nextStored, navigatorLanguage);
    if (nextStored === stored && nextResolved === current) return current;
    stored = nextStored;
    current = nextResolved;
    try {
      storage?.setItem?.(STORAGE_KEY, stored);
    } catch {
      // Locale still changes for the current page when persistence is unavailable.
    }
    refresh();
    for (const subscriber of subscribers) subscriber(current);
    return current;
  }

  refresh();
  return {
    /** Returns the resolved locale code (e.g. 'en', 'tr'). Always a real language. */
    locale: () => current,
    /** Returns the stored preference which may be 'auto'. Use for the locale selector UI. */
    storedLocale: () => stored,
    t,
    setLocale,
    refresh,
    subscribe(listener) {
      subscribers.add(listener);
      return () => subscribers.delete(listener);
    },
    destroy() {
      subscribers.clear();
    },
  };
}
